const { Pool } = require('pg');

// Initialize the PostgreSQL Pool
const isLocalhost = (process.env.DATABASE_URL || '').includes('localhost');

const sslConfig = isLocalhost
    ? false
    : process.env.DATABASE_CA_CERT
        ? { rejectUnauthorized: true, ca: process.env.DATABASE_CA_CERT }
        : { rejectUnauthorized: process.env.DB_SSL_REJECT_UNAUTHORIZED === 'true' };

const pool = new Pool({
    connectionString: process.env.DATABASE_URL || 'postgresql://localhost/kitchensync',
    max: Number(process.env.DB_POOL_MAX) || 20,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 10000,
    // Render external connections require SSL. Local Postgres usually doesn't.
    ssl: sslConfig
});

pool.on('error', (err) => {
    // Log idle client errors without terminating the entire Express server;
    // pg.Pool automatically evicts the disconnected idle client and reconnects on next query.
    console.error('[PostgreSQL Pool] Idle client error (evicted automatically):', err.message);
});

// Initialize Schema
const init = async () => {
    try {
        // Users Table
        await pool.query(`
            CREATE TABLE IF NOT EXISTS users (
                id SERIAL PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                subscription_tier TEXT DEFAULT 'free',
                credits INTEGER DEFAULT 5,
                preferences JSONB DEFAULT '{}'
            )
        `);

        // Household Sharing & Stripe Data
        await pool.query(`
            ALTER TABLE users ADD COLUMN IF NOT EXISTS household_id TEXT;
            ALTER TABLE users ADD COLUMN IF NOT EXISTS stripe_customer_id TEXT;
            ALTER TABLE users ADD COLUMN IF NOT EXISTS invite_code TEXT UNIQUE;
        `);

        // Recipes Table
        // Note: SQLite used JSON, Postgres uses JSONB for better indexing
        // We use INTEGER for foreign keys generated by SERIAL
        await pool.query(`
            CREATE TABLE IF NOT EXISTS recipes (
                id SERIAL PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                data JSONB NOT NULL,
                is_favorite BOOLEAN DEFAULT false
            )
        `);

        // Pantry Table
        await pool.query(`
            CREATE TABLE IF NOT EXISTS pantry (
                id SERIAL PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                quantity REAL,
                unit TEXT,
                category TEXT,
                expiry_date TEXT
            )
        `);

        await pool.query(`
            ALTER TABLE pantry ADD COLUMN IF NOT EXISTS expiry_date TEXT;
        `);

        // Manual Shopping List Table
        await pool.query(`
            CREATE TABLE IF NOT EXISTS shopping_list (
                id SERIAL PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                quantity REAL,
                unit TEXT,
                category TEXT
            )
        `);

        // Meal Plans Table (keyed by household_id, with OCC version counter)
        await pool.query(`
            CREATE TABLE IF NOT EXISTS meal_plans (
                household_id TEXT PRIMARY KEY,
                data JSONB NOT NULL DEFAULT '{}',
                version BIGINT NOT NULL DEFAULT 1,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        await pool.query(`
            ALTER TABLE meal_plans ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 1;
        `);

        // Idempotent Stripe Webhook Inbox (U-04)
        await pool.query(`
            CREATE TABLE IF NOT EXISTS stripe_webhook_events (
                event_id TEXT PRIMARY KEY,
                event_type TEXT NOT NULL,
                processed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Append-Only Transactional Credit Ledger (U-04)
        await pool.query(`
            CREATE TABLE IF NOT EXISTS credit_ledger (
                id SERIAL PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                delta INTEGER NOT NULL,
                balance_after INTEGER NOT NULL,
                operation TEXT NOT NULL,
                idempotency_key TEXT UNIQUE,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Content-Addressable Recipe URL Cache (U-05)
        await pool.query(`
            CREATE TABLE IF NOT EXISTS recipe_url_cache (
                url_hash TEXT PRIMARY KEY,
                canonical_url TEXT NOT NULL,
                recipe_data JSONB NOT NULL,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // Performance Indexes
        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_recipes_user_id ON recipes(user_id);
            CREATE INDEX IF NOT EXISTS idx_pantry_user_id ON pantry(user_id);
            CREATE INDEX IF NOT EXISTS idx_shopping_user_id ON shopping_list(user_id);
            CREATE INDEX IF NOT EXISTS idx_users_household_id ON users(household_id);
            CREATE INDEX IF NOT EXISTS idx_credit_ledger_user_id ON credit_ledger(user_id);
        `);

        console.log('PostgreSQL Database initialized');
    } catch (err) {
        console.error('Failed to initialize database schema:', err);
    }
};

// Auto-run schema init (skip during unit test runs)
if (!process.execArgv.includes('--test') && !process.env.NODE_TEST_CONTEXT && process.env.NODE_ENV !== 'test') {
    init();
}

// Export the pool so we can use pool.query in routes
module.exports = pool;
